def make_pdf(path, paras):
    doc = fitz.open()
    text = "\n\n".join(paras)
    per = 1000
    for i in range(0, len(text), per):
        page = doc.new_page()
        rect = fitz.Rect(56, 56, page.rect.width - 56, page.rect.height - 56)
        page.insert_textbox(rect, text[i:i + per], fontname="china-s", fontsize=11, lineheight=1.6)
    doc.save(path)
    doc.close()

